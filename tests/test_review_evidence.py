def test_병합된_변경의_리뷰_코멘트를_근거로_고정하고_인용을_허용한다(tmp_cfg):
    head = _repo(tmp_cfg)
    _import(tmp_cfg)
    _sections(tmp_cfg, [GUARD, WHY])
    model = _model(tmp_cfg, head)
    record = model.evidence["queue/depth/why"]
    assert record["status"] == "available", record
    assert record["origin"] == "review-comment" and record["merged_revision"] == head
    assert record["file"] == f"@review/{CHANGE[:9]}/c2.txt" and record["text"] == REPLY
    assert (record["author"], record["reviewed_path"], record["comment_type"]) == ("Author B", "src/queue.cpp", "inline")
    cite = f"{record['file']}:1"
    assert cite in model.citations() and extract_citations(f"거절합니다 `{cite}`.") == [cite]
    blocks, gaps = topic_blocks(model, "queue", tmp_cfg.sections()[0]["design_topics"][0])
    assert gaps == [] and "리뷰 당시의 논의이며 현재 동작의 근거가 아닙니다" in blocks[1].text
    detail = _source_detail(record, "why")
    assert "리뷰 기록" in detail and "4242" in detail and "merged_revision" in detail
    rendered, _, _ = _render(f"이유입니다 `{cite}`.", "a.md", set(), model, "https://host/repo", head)
    assert "https://host" not in rendered


def test_병합되지_않았거나_찾을_수_없는_코멘트는_검토_대상으로_남긴다(tmp_cfg):
    # 본문에서 Change-Id를 언급했을 뿐 trailer로 선언하지 않은 커밋은 병합 근거가 아니다.
    head = _repo(tmp_cfg, f"Mention review\n\nSee {CHANGE} for discussion.\n")
    _import(tmp_cfg)
    _sections(tmp_cfg, [WHY, {**WHY, "id": "gone", "comment": "zz"}, {**WHY, "id": "absent", "change": OTHER},
                        {**WHY, "id": "stale", "sha256": "0" * 64}])
    model = _model(tmp_cfg, head)
    reasons = {key.rsplit("/", 1)[1]: rec.get("reason", "") for key, rec in model.evidence.items()}
    assert all(rec["status"] == "needs-review" for rec in model.evidence.values())
    assert "병합된 커밋이 없습니다" in reasons["why"]
    assert "코멘트 id가 없습니다" in reasons["gone"]
    assert "스냅숏이 없습니다" in reasons["absent"]
    assert not any(c.startswith("@review/") for c in model.citations())


def test_리뷰_근거_설정은_변경_코멘트_앵커만_받는다():
    def errors(source):
        return configuration_errors({"id": "s", "design_topics": [{"id": "t", "sources": [source]}]})
    assert errors(WHY) == []
    assert any("change" in e for e in errors({**WHY, "change": "I123"}))
    assert any("comment" in e for e in errors({**WHY, "comment": ""}))
    assert any("file" in e for e in errors({**WHY, "file": "src/queue.cpp"}))


def test_후보에_리뷰_코멘트를_붙이고_한_줄_코멘트도_근거로_등록할_수_있다(tmp_cfg):
    head = _repo(tmp_cfg)
    _import(tmp_cfg)
    _sections(tmp_cfg, [GUARD])
    report = history_candidates.collect(tmp_cfg, _model(tmp_cfg, head))
    candidate = report["topics"][0]["excerpts"][0]["candidates"][0]
    review = candidate["reviews"]
    assert review["status"] == "available" and review["number"] == 4242
    order = [c["id"] for c in review["comments"]]
    assert order[:2] == ["c1", "c2"] and order[-1] == "m1"
    by_id = {c["id"]: c for c in review["comments"]}
    assert by_id["m1"]["signals"] == ["Gerrit 자동 알림"] and by_id["c1"]["same_file"] is True
    assert by_id["c3"]["anchors"] is None
    snippet = yaml.safe_load(history_candidates._review_snippet(CHANGE, by_id["c2"]))[0]
    _sections(tmp_cfg, [GUARD, snippet])
    model = _model(tmp_cfg, head)
    assert model.evidence[f"queue/depth/{snippet['id']}"]["text"] == REPLY
    again = history_candidates.collect(tmp_cfg, model)
    linked = {c["id"]: c for c in again["topics"][0]["excerpts"][0]["candidates"][0]["reviews"]["comments"]}
    assert linked["c2"]["already_linked"] is True
    text = history_candidates.markdown(again)
    assert "kind: review" in text and "Gerrit 자동 알림" in text


def test_스냅숏이_없으면_리뷰_링크에서_찾은_주소로_가져오기_명령을_보인다(tmp_cfg):
    head = _repo(tmp_cfg)
    _sections(tmp_cfg, [GUARD])
    report = history_candidates.collect(tmp_cfg, _model(tmp_cfg, head))
    review = report["topics"][0]["excerpts"][0]["candidates"][0]["reviews"]
    assert review == {"status": "missing", "change_id": CHANGE, "base_url": "https://gerrit.example.invalid"}
    text = history_candidates.markdown(report)
    assert f"https://gerrit.example.invalid/a/changes/{CHANGE}?o=MESSAGES" in text and "import-reviews" in text


def test_가져오기_명령은_설정의_리뷰_디렉터리에만_쓴다(tmp_cfg, tmp_path, capsys):
    change, comments = tmp_path / "change.json", tmp_path / "comments.json"
    change.write_bytes(_change())
    comments.write_bytes(_comments())
    assert main(["--config", str(tmp_cfg.root / "sdd.yaml"), "import-reviews",
                 "--change", str(change), "--comments", str(comments)]) == 0
    assert (tmp_cfg.root / "reviews" / f"{CHANGE}.json").is_file()
    assert "공개 저장소에 올리지 마세요" in capsys.readouterr().out



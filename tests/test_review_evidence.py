CHANGE = "I" + "1234567890abcdef" * 2 + "12345678"
OTHER = "I" + "f" * 40
CODE = "int Queue::push(Request *r)\n{\n\tif (depth_ >= 4)\n\t\treturn -EBUSY;\n\titems_.push_back(r);\n\treturn 0;\n}\n"
MESSAGE = f"""Add frame queue with bounded depth

The sensor driver drops frames beyond four queued buffers.

Change-Id: {CHANGE}
Reviewed-on: https://gerrit.example.invalid/c/hal/+/4242
"""
INLINE = "Why reject instead of blocking the caller?\nBlocking here would stall the request thread."
REPLY = "Blocking stalls the request thread; rejecting keeps it responsive."


def _change(messages=True, **extra):
    data = {"id": "hal~main~" + CHANGE, "project": "hal", "branch": "main", "change_id": CHANGE,
            "subject": "Add frame queue with bounded depth", "_number": 4242, **extra}
    if messages:
        data["messages"] = [
            {"id": "m1", "author": {"name": "Reviewer A", "email": "a@example.invalid"},
             "date": "2026-01-02 10:00:00.000000000", "message": "Uploaded patch set 1.",
             "_revision_number": 1, "tag": "autogenerated:gerrit:newPatchSet"},
            {"id": "m2", "author": {"username": "author-b"}, "date": "2026-01-03 10:00:00.000000000",
             "message": "Patch Set 2:\n\nThe depth limit follows the driver documentation.", "_revision_number": 2},
        ]
    return (")]}'\n" + json.dumps(data)).encode()


def _comments(reply=REPLY):
    data = {"src/queue.cpp": [
        {"id": "c1", "author": {"name": "Reviewer A"}, "updated": "2026-01-02 11:00:00.000000000",
         "message": INLINE, "line": 3, "patch_set": 1, "unresolved": False},
        {"id": "c2", "author": {"name": "Author B"}, "updated": "2026-01-02 12:00:00.000000000",
         "message": reply, "line": 3, "patch_set": 1, "in_reply_to": "c1", "unresolved": False},
    ], "/COMMIT_MSG": [
        {"id": "c3", "author": {"name": "Reviewer A"}, "updated": "2026-01-02 13:00:00.000000000",
         "message": "Done", "line": 1, "patch_set": 1},
    ]}
    return (")]}'\n" + json.dumps(data)).encode()


def _git(root, *args):
    return subprocess.check_output(["git", "-C", str(root), *args], encoding="utf-8").strip()


def _commit(root, files, message):
    for name, text in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    _git(root, "add", "-A")
    _git(root, "-c", "user.name=T", "-c", "user.email=t@example.invalid", "-c", "core.autocrlf=false",
         "commit", "-q", "-m", message)
    return _git(root, "rev-parse", "HEAD")


def _repo(cfg, message=MESSAGE):
    _git(cfg.source_root, "init", "-q")
    return _commit(cfg.source_root, {"src/queue.cpp": CODE}, message)


def _import(cfg, change=None, comments=None):
    snapshot = review_evidence.normalize(change or _change(), comments if comments is not None else _comments())
    return review_evidence.write(cfg.reviews_dir, snapshot)


GUARD = {"id": "guard", "file": "src/queue.cpp", "start": "\tif (depth_ >= 4)", "end": "\titems_.push_back(r);"}
WHY = {"id": "why", "kind": "review", "change": CHANGE, "comment": "c2",
       "start": "Blocking stalls", "end": "keeps it responsive."}


def _sections(cfg, sources):
    sec = {"id": "queue", "design_topics": [{"id": "depth", "question": "왜 거절합니까?", "sources": sources}]}
    cfg.sections_file.write_text(yaml.safe_dump({"sections": [sec]}, allow_unicode=True), encoding="utf-8")


def _model(cfg, head):
    model = KnowledgeModel(meta={"source_commit": head})
    collect(cfg, model)
    return model


def test_응답의_접두어를_걷어내고_메시지와_인라인_코멘트를_이메일_없이_정규화한다():
    snapshot = review_evidence.normalize(_change(), _comments())
    assert snapshot["change_id"] == CHANGE and snapshot["number"] == 4242 and snapshot["project"] == "hal"
    by_id = {c["id"]: c for c in snapshot["comments"]}
    assert set(by_id) == {"m1", "m2", "c1", "c2", "c3"}
    assert by_id["c2"]["type"] == "inline" and by_id["c2"]["in_reply_to"] == "c1" and by_id["c2"]["path"] == "src/queue.cpp"
    assert by_id["m1"]["author"] == "Reviewer A" and by_id["m2"]["author"] == "author-b"
    assert "example.invalid" not in json.dumps(snapshot)
    assert [c["id"] for c in snapshot["comments"]] == ["m1", "c1", "c2", "c3", "m2"]


